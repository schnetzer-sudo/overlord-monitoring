-- ⚠️ DER PROZESSFILTER IN DIESER SITZUNG IST NICHT AUSSAGEKRAEFTIG, UND DAS IST BELEGT.
--    Er steht hier als `m.ProcessID IN (@p1, @p2, @p3)` — mit Sitzungsvariablen, um keine
--    Kennung ins Skript zu schreiben (G1). Darauf fuehrt MariaDB KEINE Bereichsanalyse aus:
--    ProejctIDIDX bleibt in possible_keys und wird nie als Bereich genutzt. Gemessen ist damit
--    nicht der Prozessfilter, sondern seine Abwesenheit.
--    Die gueltigen Zahlen stehen in a1-gegenprobe-prozessfilter-*.sql, wo die Kennungen als
--    LITERALE im Statement stehen — dieselbe Form, die der Treiber auf die Leitung legt.
--    Die uebrigen Faelle dieser Sitzung (24 h, 7 Tage, Statusfilter) sind davon nicht beruehrt.
--
-- G1, Z1, Huelle und Laufzeitermittlung wie in den Sitzungen a1-*-f*.sql; die
-- Begruendung steht dort im Kopf und wird hier nicht wiederholt.
--
-- Fassung 0 ist die heutige Fassung, Fassung 4 traegt
--   IGNORE INDEX FOR JOIN (ProejctIDIDX, Message_ProcessFK)
-- auf `Message` und sonst nichts.

SELECT '=== 00 read_only (erste Abfrage der Sitzung) ===' AS marke;
SELECT @@global.read_only AS read_only, NOW() AS serverzeit;

SET max_statement_time = 60;
SET profiling = 1;
SET profiling_history_size = 100;



-- ── Drei Prozesse des Mandanten, deterministisch gewaehlt ───────────────────
-- Die drei mit den meisten Nachrichten im 30-Tage-Fenster, bei Gleichstand nach
-- der Kennung. G1: Sie bleiben in Sitzungsvariablen und werden nie ausgegeben.
-- Gelesen wird aus `message_rollup` und nicht aus `Message` — dieselbe Menge,
-- ohne einen weiteren Durchlauf ueber die Quelle (Regel L2).
SET @p1 = NULL, @p2 = NULL, @p3 = NULL;

SELECT r.process_id INTO @p1 FROM overlord_monitor.message_rollup r
  JOIN GlassfishDB.Process p ON p.ProcessID = r.process_id
  JOIN GlassfishDB.ProjectMandant pm ON pm.ProjectID = p.ProjectID
 WHERE pm.MandantID = 'NEXANS'
   AND r.stunde >= '2025-11-30 04:09:47' AND r.stunde < '2025-12-30 04:09:47'
 GROUP BY r.process_id ORDER BY SUM(r.anzahl) DESC, r.process_id LIMIT 0, 1;
SELECT r.process_id INTO @p2 FROM overlord_monitor.message_rollup r
  JOIN GlassfishDB.Process p ON p.ProcessID = r.process_id
  JOIN GlassfishDB.ProjectMandant pm ON pm.ProjectID = p.ProjectID
 WHERE pm.MandantID = 'NEXANS'
   AND r.stunde >= '2025-11-30 04:09:47' AND r.stunde < '2025-12-30 04:09:47'
 GROUP BY r.process_id ORDER BY SUM(r.anzahl) DESC, r.process_id LIMIT 1, 1;
SELECT r.process_id INTO @p3 FROM overlord_monitor.message_rollup r
  JOIN GlassfishDB.Process p ON p.ProcessID = r.process_id
  JOIN GlassfishDB.ProjectMandant pm ON pm.ProjectID = p.ProjectID
 WHERE pm.MandantID = 'NEXANS'
   AND r.stunde >= '2025-11-30 04:09:47' AND r.stunde < '2025-12-30 04:09:47'
 GROUP BY r.process_id ORDER BY SUM(r.anzahl) DESC, r.process_id LIMIT 2, 1;

-- Hat der Mandant weniger als drei Prozesse, wird der erste wiederholt: eine
-- IN-Liste mit dreimal demselben Wert ist dieselbe Menge wie mit einem.
SET @p2 = COALESCE(@p2, @p1), @p3 = COALESCE(@p3, @p1);

SELECT '=== Prozesswahl gesetzt (ohne Kennungen) ===' AS marke;
SELECT @p1 IS NOT NULL AS p1_da, @p2 IS NOT NULL AS p2_da, @p3 IS NOT NULL AS p3_da,
       (@p1 <=> @p2) AS p1_gleich_p2, (@p2 <=> @p3) AS p2_gleich_p3;


